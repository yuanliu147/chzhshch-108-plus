def fig_buy2_cases():
    g = Figure('fig-buy2-cases', '第二类买点的三种情况（第101课）',
               '最强：一买后次级别走势凌厉上破最后一个中枢，回试不触及中枢，二买与三买合一，常对应V型反转。'
               '一般：一买、二买、三买依次向上。最弱：二买跌破一买，这里一般构成盘整背驰，原文明确这是完全可以的。',
               760, 262)
    cases = [
        (8, '最强：二买＝三买', [(0, 15), (1, 12), (2, 14), (3, 12), (4, 9), (5, 15.5), (6, 18), (7, 14.5), (8, 19), (9, 21)],
         (0, 3, 12, 14), [(4, 9, '一买'), (7, 14.5, '二买＝三买')], '回试14.5不触及中枢上沿14'),
        (262, '一般：依次向上', [(0, 15), (1, 12), (2, 14), (3, 9), (4, 12), (5, 10.5), (6, 13), (7, 11), (8, 13.5), (9, 16), (10, 14.5), (11, 18)],
         (5, 8, 11, 13), [(3, 9, '一买'), (5, 10.5, '二买'), (10, 14.5, '三买')], '9 ＜ 10.5 ＜ 14.5'),
        (516, '最弱：二买低于一买', [(0, 15), (1, 12), (2, 14), (3, 10), (4, 13), (5, 8.5), (6, 11), (7, 13), (8, 12), (9, 15)],
         (0, 3, 12, 14), [(3, 10, '一买'), (5, 8.5, '二买')], '8.5 ＜ 10，一般构成盘整背驰'),
    ]
    for x0, title, pts, zn, marks, note in cases:
        g.ptitle(x0 + 2, 26, title)
        p = g.panel(x0, 36, 236, 200, 7, 22, len(pts), pad_l=28, pad_r=10, pad_t=18, pad_b=24)
        p.axis(ticks=[9, 12, 15, 18, 21])
        p.zone(zn[0], zn[1], zn[2], zn[3], 'zone')
        p.path(pts, 'path')
        for i, v, lab in marks:
            p.dot(i, v, 'buypoint', 5.5)
            p.tag(i, v, lab, 'ts', dy=18 if v < 12 else -13)
        g.text(x0 + 2, 252, note, 'ts')
    g.caption('第101课原文：第二类买点跌破第一类买点，也就是第二类买点比第一类买点低，这是完全可以的。')
    g.caption('把“二买必须高于一买”当成原版硬条件会漏掉弱情况；若要排除，应标成你自己的过滤器并单独检验。人工示意。', 'ts')
    return g


def fig_points_map():
    g = Figure('fig-points-map', '买卖点与中枢的位置关系（完备性）',
               '中枢之下对应转折，只在下跌确立后出现第一类买点；中枢之上对应延续，出现第三类买点；'
               '第二类买点位置不限。一买与二买、一买与三买不可能重合，只有二买与三买可以重合。',
               760, 246)
    g.ptitle(12, 26, '所有买卖点都对应着与该级别最靠近的一个中枢的关系')
    p = g.panel(10, 36, 430, 200, 6, 18, 12, pad_l=30, pad_r=14, pad_t=18, pad_b=24)
    p.axis(ticks=[8, 11, 14, 17])
    p.zone(2, 8, 10, 13, 'zone')
    p.hline(13, 2, 8, 'zgedge')
    p.hline(10, 2, 8, 'zdedge')
    p.path([(0, 8), (1, 10.5), (2, 12), (3, 10.5), (4, 12.5), (5, 11), (6, 13), (7, 11.5), (8, 15), (9, 17), (10, 14), (11, 16)], 'path')
    p.tag(5, 15.6, '中枢之上：延续 → 三买', 'tb', dy=0)
    p.tag(5, 8.4, '中枢之下：转折 → 一买', 'tb', dy=0)
    p.dot(0, 8, 'buypoint', 5)
    p.dot(9, 17, 'sellpoint', 5)
    rows = [
        ('一买', '下跌确立后，中枢之下的背驰转折点'),
        ('二买', '一买后次级别回试的结束点，位置可上可下'),
        ('三买', '中枢之上，离开后首次回试不破ZG'),
        ('重合', '一买≠二买、一买≠三买；二买可与三买重合'),
        ('注意', '上涨趋势确立后，该级别只有三买'),
    ]
    for k, (a, b) in enumerate(rows):
        y = 58 + k * 34
        g.text(462, y, a, 'tb')
        g.text(504, y, b, 'ts')
    g.caption('第21课：中枢延续时，中枢之上只可能有卖点；中枢扩张或新生时，中枢之上才存在第三类买点。')
    g.caption('第21课完备性定理（作者观点）：市场必然产生赢利的买卖点，只有第一、二、三类。本次未做收益检验。人工示意。', 'ts')
    return g