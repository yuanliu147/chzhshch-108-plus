def fig_center_break():
    g = Figure('fig-center-break', '第三类买点判定：离开＋首次回试＋不跌破ZG',
               '合格：次级别走势向上离开中枢10至13到18，再以一个次级别走势回试到14.5，低点不跌破ZG等于13，构成第三类买点。'
               '不合格一：回试到11.5重新跌回中枢，中枢延续，不是三买。'
               '不合格二：第一次回试13.5已是三买，其后第N次回调14.5不再具备首次性，不是三买。',
               760, 272)
    cases = [
        (8, '✓ 首次回试不破ZG → 三买',
         [(0, 13), (1, 10), (2, 13), (3, 10), (4, 12), (5, 11), (6, 15), (7, 18), (8, 16), (9, 14.5), (10, 17), (11, 20)],
         9, 14.5, '三买', True, (0, 5)),
        (262, '✗ 回试跌回中枢 → 延伸',
         [(0, 13), (1, 10), (2, 13), (3, 10), (4, 12), (5, 11), (6, 15), (7, 18), (8, 14), (9, 11.5), (10, 13), (11, 12)],
         9, 11.5, '跌回中枢', False, (0, 5)),
        (516, '✗ 不是第一次 → 不算三买',
         [(0, 13), (1, 10), (2, 13), (3, 10), (4, 12), (5, 16), (6, 13.5), (7, 17), (8, 15), (9, 18), (10, 14.5), (11, 17)],
         10, 14.5, '第N次回调', False, (0, 4)),
    ]
    for x0, title, pts, mi, mv, lab, ok, zi in cases:
        g.ptitle(x0 + 2, 26, title)
        p = g.panel(x0, 36, 236, 210, 9, 21, 12, pad_l=28, pad_r=10, pad_t=16, pad_b=24)
        p.axis(ticks=[10, 13, 16, 19])
        p.zone(zi[0], zi[1], 10, 13, 'zone')
        p.hline(13, 0, 11, 'zgedge')
        p.path(pts, 'path')
        p.dot(mi, mv, 'buypoint' if ok else 'badpoint', 6)
        p.tag(mi, mv, lab, 'tb', dy=20 if ok or x0 == 262 else -14)
        if x0 == 516:
            p.dot(6, 13.5, 'buypoint', 5)
            p.tag(6, 13.5, '首次＝三买', 'ts', dy=-13)
            p.cross(mi, mv, 'bad')
        if x0 == 262:
            p.cross(mi, mv, 'bad')
        g.text(x0 + 2, 262, 'ZG＝13（中枢上沿）', 'ts')
    g.caption('第20课：一个次级别走势类型向上离开中枢，然后以一个次级别走势类型回试，其低点不跌破ZG，则构成第三类买点；必须是第一次。')
    g.caption('第18课中枢定理三：中枢破坏，当且仅当一个次级别走势离开后，其后的次级别回抽不重新回到该中枢内。', 'ts')
    g.caption('第51课署名回复：这里说的走势类型，都必须是完成的。卖点方向相反：回抽高点不升破ZD。人工示意。', 'ts')
    return g


