def fig_center_bounds():
    g = Figure('fig-center-bounds', '核心边界与外围边界：ZG/ZD 与 GG/DD 不是一回事',
               '与中枢方向一致的次级别走势称Z走势段。Z1区间9至13、Z2区间10至14、Z3区间11至12.5。'
               'ZG取前两段高点较小者13，ZD取前两段低点较大者10；GG取所有段高点最大者14，DD取所有段低点最小者9，'
               'G为所有段高点最小者12.5，D为所有段低点最大者11。第三类买点看ZG，不是GG。',
               760, 266)
    g.ptitle(12, 26, 'Z走势段＝与中枢形成方向一致的次级别走势')
    p = g.panel(10, 36, 470, 220, 8, 15, 6, pad_l=32, pad_r=14, pad_t=18, pad_b=26)
    p.axis(ticks=[9, 11, 13, 14], xlabels=[(0, 'd1'), (1, 'g1'), (2, 'd2'), (3, 'g2'), (4, 'd3'), (5, 'g3')])
    p.band(9, 14, 'out', 0, 5)
    p.band(10, 13, 'zone', 0, 5)
    p.path([(0, 9), (1, 13), (2, 10), (3, 14), (4, 11), (5, 12.5)], 'path')
    for i0, i1, s in ((0, 1, 'Z1'), (2, 3, 'Z2'), (4, 5, 'Z3')):
        p.segline(i0, [9, 13, 10, 14, 11, 12.5][i0], i1, [9, 13, 10, 14, 11, 12.5][i1], 'segA')
        p.tag((i0 + i1) / 2.0, 8.4, s, 'tb', dy=0)
    for v, cls in ((13, 'zgedge'), (10, 'zdedge'), (14, 'ggline'), (9, 'ddline')):
        p.hline(v, 0, 5, cls)
    legend = [
        ('ZG＝13', '前两个Z段高点取小 → 中枢上沿', 'zgedge'),
        ('ZD＝10', '前两个Z段低点取大 → 中枢下沿', 'zdedge'),
        ('GG＝14', '所有Z段高点取大 → 外围最高', 'ggline'),
        ('DD＝9', '所有Z段低点取小 → 外围最低', 'ddline'),
        ('G＝12.5', '所有Z段高点取小', 'ts'),
        ('D＝11', '所有Z段低点取大', 'ts'),
    ]
    for k, (a, b, c) in enumerate(legend):
        y = 58 + k * 34
        g.line(500, y - 4, 522, y - 4, c if c != 'ts' else 'aux')
        g.text(530, y, a, 'tb')
        g.text(530, y + 16, b, 'ts')
    g.caption('第20课定义 GG=max(gn)、G=min(gn)、D=max(dn)、DD=min(dn)，ZG=min(g1,g2)、ZD=max(d1,d2)。')
    g.caption('第32—33课把实例中的2915更正为外围GG而非ZG。用外围高点当三买的中枢边界，会改变策略含义。人工示意。', 'ts')
    return g


