def _zig(g, x, y, w, h, pts, pmin, pmax, n=None, labels=None, seg_upto=None):
    p = g.panel(x, y, w, h, pmin, pmax, n or len(pts), pad_l=32, pad_r=14, pad_t=18, pad_b=24)
    p.axis(ticks=[pmin + 1 + k * 3 for k in range(int((pmax - pmin) / 3) + 1)])
    p.path(pts, 'path')
    if seg_upto is not None:
        p.path(pts[:seg_upto + 1], 'seg')
    if labels:
        for k, (i, v, s, cls) in enumerate(labels):
            p.tag(i, v, s, cls, dy=-13 if k % 2 == 0 else 17)
    return p


