def fig_seg_feature():
    g = Figure('fig-seg-feature', '特征序列：向上线段取向下笔',
               '向上笔开始的线段记为S1X1S2X2S3X3，其中S为向上笔、X为向下笔。'
               '取X1区间12至15、X2区间14至18、X3区间16至20作为特征序列，'
               '依次抬高无包含，已是标准特征序列，没有出现顶分型，所以线段还在延伸。',
               760, 290)
    pts = [(0, 10), (1, 15), (2, 12), (3, 18), (4, 14), (5, 20), (6, 16)]
    g.ptitle(12, 26, '笔序列：S＝向上笔，X＝向下笔')
    p = g.panel(10, 36, 430, 210, 9, 21, 7, pad_l=32, pad_r=14, pad_t=18, pad_b=24)
    p.axis(ticks=[10, 13, 16, 19])
    for k in range(6):
        p.segline(pts[k][0], pts[k][1], pts[k + 1][0], pts[k + 1][1], 'bi' if k % 2 == 0 else 'seg')
    for k, (i, v) in enumerate(pts):
        p.dot(i, v, 'toppoint' if k % 2 else 'botpoint', 4)
    for k, s in enumerate(['S1', 'X1', 'S2', 'X2', 'S3', 'X3']):
        i0, v0 = pts[k]
        i1, v1 = pts[k + 1]
        p.tag((i0 + i1) / 2.0, (v0 + v1) / 2.0, s, 'tb', dy=-4 if k % 2 == 0 else 16,
              dx=10 if k % 2 == 0 else -10)
    g.text(12, 262, '向上线段只看向下笔 X1、X2、X3；向下线段只看向上笔。', 'ts')
    g.arrow(448, 140, 470, 140)
    g.ptitle(478, 26, '特征序列（每元素当成一根K线）')
    q = g.panel(476, 36, 274, 210, 9, 21, 3, pad_l=32, pad_r=14, pad_t=18, pad_b=24)
    q.axis(ticks=[12, 15, 18], xlabels=[(0, 'X1'), (1, 'X2'), (2, 'X3')])
    q.bars([(12, 15), (14, 18), (16, 20)], 'fs')
    q.tag(0, 15, '[12,15]', 'ts', dy=-10)
    q.tag(1, 18, '[14,18]', 'ts', dy=-10)
    q.tag(2, 20, '[16,20]', 'ts', dy=-10)
    g.text(478, 262, '无包含 → 已是标准特征序列', 'ts')
    g.text(478, 280, '没有顶分型 → 线段未结束', 'ts')
    g.caption('第67课：特征序列相邻元素之间没有重合区间，称为该序列的一个缺口（不是K线跳空）。')
    return g


