def fig_divergence():
    g = Figure('fig-divergence', '趋势背驰：A、B、C 三段与 MACD 面积比较',
               '下跌趋势中先有中枢1区间19.5至21，A段下跌到15，随后中枢2区间15至17.5把MACD黄白线回拉到0轴附近，'
               'C段再跌到10创新低，但C段对应的绿柱面积明显小于A段，构成趋势背驰，其转折位置就是第一类买点。',
               760, 432)
    pts = [(0, 22), (1, 19), (2, 21), (3, 19.5), (4, 20.5), (5, 17.5), (6, 15), (7, 17.5),
           (8, 15), (9, 16.5), (10, 12.5), (11, 10), (12, 13.5), (13, 12), (14, 15.5)]
    g.ptitle(12, 26, '价格：两个同级别中枢 → 下跌趋势 → C段创新低')
    p = g.panel(10, 36, 740, 210, 9, 23, 15, pad_l=34, pad_r=16, pad_t=18, pad_b=24)
    p.axis(ticks=[10, 13, 16, 19, 22])
    p.zone(0, 4, 19.5, 21, 'zone')
    p.zone(6, 9, 15, 17.5, 'zone')
    p.path(pts, 'path')
    p.segline(4, 20.5, 6, 15, 'segA')
    p.segline(9, 16.5, 11, 10, 'segC')
    p.tag(2, 21.6, '中枢1', 'tb', dy=0)
    p.tag(7.5, 18.1, '中枢2（B）', 'tb', dy=0)
    p.tag(5, 18.6, 'A段', 'tb', dy=0)
    p.tag(10, 14.4, 'C段', 'tb', dy=0)
    p.dot(11, 10, 'buypoint', 6.5)
    p.tag(11, 10, '一买（背驰点）', 'tb', dy=20)
    p.tag(13, 11.4, '背驰后≠马上大涨', 'ts', dy=0)
    vals = [0.3, -0.2, 0.4, -0.1, 0.2, -1.2, -2.0, 0.3, -0.4, 0.2, -0.7, -0.9, 0.8, 0.3, 1.0]
    diff = [0.5, 0.2, 0.6, 0.3, 0.35, -0.8, -1.6, -0.2, -0.5, 0.05, -0.6, -0.95, 0.2, 0.15, 0.8]
    dea = [0.4, 0.35, 0.45, 0.4, 0.38, -0.25, -0.95, -0.6, -0.55, -0.25, -0.45, -0.7, -0.15, 0.0, 0.4]
    g.ptitle(12, 274, 'MACD（12,26,9）：B段把黄白线回拉到0轴附近，C段绿柱面积＜A段')
    m = macd_panel(g, 10, 284, 740, 140, vals, 2.6)
    m.path(list(enumerate(diff)), 'diff')
    m.path(list(enumerate(dea)), 'dea')
    for i0, i1, lab in ((4.55, 6.45, 'A段面积'), (9.55, 11.45, 'C段面积＜A')):
        x0, x1 = m.X(i0) - m.dx / 2, m.X(i1) + m.dx / 2
        g.rect(x0, m.Y(0), x1 - x0, m.Y(-2.2) - m.Y(0), 'area')
        g.text((x0 + x1) / 2, m.Y(1.9), lab, 'tb', 'middle')
    g.text(600, 298, '黄白线：DIFF / DEA', 'ts')
    g.caption('第24课：A、B、C在一个大趋势里，A之前已有一个中枢，B是另一个中枢并把黄白线回拉0轴，C段柱子面积小于A段 → 标准背驰。')
    g.caption('第25课：MACD与均线只能是辅助性工具。第27课：趋势背驰至少发生在第二个同级别中枢之后。人工合成数值，不是任何标的行情。', 'ts')
    return g


