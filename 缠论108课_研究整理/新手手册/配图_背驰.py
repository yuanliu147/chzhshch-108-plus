def fig_qujiantao():
    g = Figure('fig-qujiantao', '区间套：大级别定区域，小级别逐级缩小',
               '周线背驰段覆盖最宽的时间区间，日线背驰段落在其中并更窄，再到30分钟、5分钟、1分钟逐级收缩，'
               '最终把大级别转折点定位到一个很小的范围。级别不是无限可分，不能达到数学上唯一一点的精度。',
               760, 262)
    rows = [
        ('周线背驰段', 100, 680, '大级别背驰段（最宽）'),
        ('日线背驰段', 200, 560, '必须落在周线段内'),
        ('30分钟背驰段', 280, 470, '再缩小一层'),
        ('5分钟背驰段', 330, 420, '继续缩小'),
        ('1分钟背驰段', 355, 398, '转折范围'),
    ]
    for k, (lab, x0, x1, note) in enumerate(rows):
        y = 44 + k * 44
        g.text(12, y + 18, lab, 'tb')
        g.rect(x0, y, x1 - x0, 26, 'nest' if k < 4 else 'nestlast')
        g.text(x0 + 10 if x1 - x0 > 120 else x1 + 8, y + 18, note, 'ts')
    g.line(376, 38, 376, 252, 'now')
    g.text(382, 34, '转折位置（事后才完全清楚）', 'ts')
    g.caption('第27课：某大级别的转折点，可以通过不同级别背驰段的逐级收缩范围而确定；由于级别不是无限可分的，不可能达到数学上唯一一点的精度。')
    g.caption('每一层的背驰段都要在该层当时可确认，不能拿最终低点反过来决定上面每一层的范围。人工示意。', 'ts')
    return g