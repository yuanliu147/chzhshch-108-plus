def ck(name, cond, detail=''):
    CHECKS.append({'检查项': name, '通过': bool(cond), '说明': detail})
    if not cond:
        raise AssertionError(name + ' :: ' + detail)


def contains(a, b):
    return b[0] >= a[0] and b[1] <= a[1]


def either(a, b):
    return contains(a, b) or contains(b, a)


def merge(a, b, up):
    return (max(a[0], b[0]), max(a[1], b[1])) if up else (min(a[0], b[0]), min(a[1], b[1]))


def top3(s):
    return s[1][1] > s[0][1] and s[1][1] > s[2][1] and s[1][0] > s[0][0] and s[1][0] > s[2][0]


def bot3(s):
    return s[1][0] < s[0][0] and s[1][0] < s[2][0] and s[1][1] < s[0][1] and s[1][1] < s[2][1]


def overlap(rs):
    lo, hi = max(r[0] for r in rs), min(r[1] for r in rs)
    return (lo, hi) if lo <= hi else None


def standardize(seq, up):
    out, direction = [], up
    for iv in seq:
        if out and either(out[-1], iv):
            out[-1] = merge(out[-1], iv, direction)
        else:
            if out:
                direction = iv[1] >= out[-1][1]
            out.append(iv)
    return out


def segs(pts, i0, i1):
    """把折线顶点切成连续段，返回每段的价格区间。"""
    return [(min(pts[k][1], pts[k + 1][1]), max(pts[k][1], pts[k + 1][1]))
            for k in range(i0, i1)]


