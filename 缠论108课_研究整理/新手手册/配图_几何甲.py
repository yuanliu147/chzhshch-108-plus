def fig_fangxiang():
    g = Figure('fig-fangxiang', '合并方向从哪里来：借前一根，不是看被包含的两根',
               '四根K线区间依次为12至16、10至15、9至14、10至13。第3根包含第4根，需要合并。'
               '第2根与第3根不构成包含，用它们定方向：第3根低点9不高于第2根低点10，所以向下。'
               '正确合并取两端较低者得9至13，新低点9保住，与第2根10至15交叉、无包含。'
               '若误当成向上合并得10至14，新低点9被抹掉，而且整根又落回第2根区间里，包含关系没有消掉。',
               760, 262)
    specs = [(12, 16), (10, 15), (9, 14), (10, 13)]

    g.ptitle(12, 26, '原始四根：方向由第2、3根定')
    p = g.panel(10, 36, 240, 180, 8, 17, 4, pad_l=28, pad_r=10, pad_t=14, pad_b=26)
    p.axis(ticks=[9, 12, 15], xlabels=[(0, '1'), (1, '2'), (2, '3'), (3, '4')])
    p.zone(2, 3, 9, 14, 'out')
    p.bars(specs)
    p.hline(10, i0=1, i1=2, cls='ddline')
    p.bracket(2, 3, 14.6, '包含', 'ts')
    p.tag(1, 16, '定方向', 'tb', dy=-10)
    p.tag(1, 10, '低10', 'tb', dy=16)
    p.dot(2, 9, 'botpoint')
    p.tag(2, 9, '低9', 'tb', dy=18)
    g.text(12, 234, '第3根包含第4根 → 要合并', 'ts')
    g.text(12, 252, 'd3=9 ≤ d2=10 → 向下', 'ts')

    g.arrow(252, 126, 268, 126)
    g.ptitle(274, 26, '正确：向下合并第3、4根')
    q = g.panel(272, 36, 230, 180, 8, 17, 3, pad_l=10, pad_r=10, pad_t=14, pad_b=26)
    q.axis(xlabels=[(0, '1'), (1, '2'), (2, '新3')])
    q.bars(specs[:2])
    q.bar(2, 9, 13, 'knew')
    q.tag(2, 13, '高13', 'tb', dy=-10)
    q.dot(2, 9, 'botpoint')
    q.tag(2, 9, '低9', 'tb', dy=18)
    g.text(274, 234, '新K＝[9,13]，低点9保住', 'ts')
    g.text(274, 252, '与第2根交叉 → 无包含，完成', 'ts')

    g.arrow(504, 126, 518, 126)
    g.ptitle(522, 26, '错误：当成向上合并')
    r = g.panel(520, 36, 230, 180, 8, 17, 3, pad_l=10, pad_r=10, pad_t=14, pad_b=26)
    r.axis(xlabels=[(0, '1'), (1, '2'), (2, '错合并')])
    r.zone(1, 2, 10, 15, 'gap')
    r.bars(specs[:2])
    r.bar(2, 10, 14, 'kbad')
    r.dot(2, 9, 'badpoint')
    r.tag(2, 9, '低点9没了', 'tb', dy=18)
    r.cross(2, 15.6, 'bad')
    g.text(522, 234, '新K＝[10,14]，低点9被抹掉', 'ts')
    g.text(522, 252, '又落回第2根里 → 包含没消掉', 'ts')

    g.caption('第65课：第n根与第n+1根包含、与第n-1根不包含时，gn≥gn-1为向上，dn≤dn-1为向下。'
              '这里第2根就是第n-1根，方向由它和第3根比出来，与被包含的第3、4根自己无关，也与阴阳线无关。')
    g.caption('第62课：经过这样的处理，所有K线图都可以处理成没有包含关系的图形。右图违反了这个目标。人工示意，非行情。', 'ts')
    return g


def fig_shunxu():
    g = Figure('fig-shunxu', '包含处理必须按顺序，且不传递',
               '三根K线区间为10至14、11至13、9至13.5。第1与第2包含，第2与第3包含，但第1与第3交叉并不包含。'
               '正确做法是先合并第1、2根得到11至14，再拿新K线与第3根比较，发现无包含则各自保留。'
               '错误做法是把三根一次性合并，第3根被吞掉。',
               760, 244)
    specs = [(10, 14), (11, 13), (9, 13.5)]
    data = [
        (10, '原始三根', specs, 3, '1与2包含、2与3包含'),
        (265, '正确：逐根顺序处理', [(11, 14), (9, 13.5)], 2, '新K与第3根交叉，无包含 → 保留'),
        (520, '错误：一次性全合并', [(11, 14)], 1, '第3根被吞掉，划分就错了'),
    ]
    for x0, title, sp, n, note in data:
        g.ptitle(x0 + 2, 26, title)
        p = g.panel(x0, 36, 230, 180, 8, 15, n, pad_l=10, pad_r=10, pad_t=14, pad_b=26)
        p.axis(xlabels=[(i, str(i + 1)) for i in range(n)])
        for i, (lo, hi) in enumerate(sp):
            p.bar(i, lo, hi, 'knew' if (x0 == 265 and i == 0) else 'k')
        if x0 == 10:
            p.bracket(0, 1, 14.4, '包含', 'ts')
            p.bracket(1, 2, 8.4, '包含', 'ts', below=True)
        if x0 == 520:
            p.cross(0, 12.5, 'bad')
        g.text(x0 + 2, 234, note, 'ts')
    g.arrow(245, 126, 262, 126)
    g.arrow(500, 126, 517, 126)
    g.caption('第65课：包含关系不符合传递律。先用第1、2根合并出新K线，再用新K线去和第3根比。')
    g.caption('方向判定：第n根与第n+1根包含、与第n-1根不包含时，gn≥gn-1 为向上，dn≤dn-1 为向下。', 'ts')
    return g


def fig_fenxing():
    g = Figure('fig-fenxing', '顶分型、底分型与三根K线的完全分类',
               '顶分型例：三根区间10至13、12至16、11至14，中间根高点16最高、低点12也最高，顶为16。'
               '底分型例：11至14、8至12、10至13，中间根低点8最低、高点12也最低，底为8。'
               '下方给出无包含关系时三相邻K线的四种组合：上升K线、顶分型、下降K线、底分型。',
               760, 436)
    for x0, title, sp, pm, is_top in (
        (10, '顶分型', [(10, 13), (12, 16), (11, 14)], (9, 17), True),
        (390, '底分型', [(11, 14), (8, 12), (10, 13)], (6, 16), False),
    ):
        g.ptitle(x0 + 2, 26, title)
        p = g.panel(x0, 36, 360, 180, pm[0], pm[1], 3, pad_l=34, pad_r=14, pad_t=18, pad_b=26)
        p.axis(ticks=[pm[0] + 1 + 2 * k for k in range(4)],
               xlabels=[(0, '第1根'), (1, '第2根'), (2, '第3根')])
        p.bars(sp)
        p.bar(1, sp[1][0], sp[1][1], 'khl')
        if is_top:
            p.dot(1, sp[1][1], 'toppoint')
            p.tag(1, sp[1][1], '顶＝16', 'tb', dy=-14)
            g.text(x0 + 34, 232, '中间根：高点16＞13、14（最高）', 't')
            g.text(x0 + 34, 250, '低点12＞10、11（也最高）→ 顶分型', 'ts')
        else:
            p.dot(1, sp[1][0], 'botpoint')
            p.tag(1, sp[1][0], '底＝8', 'tb', dy=22)
            g.text(x0 + 34, 232, '中间根：低点8＜14、10（最低）', 't')
            g.text(x0 + 34, 250, '高点12＜14、13（也最低）→ 底分型', 'ts')
    g.text(12, 274, '处理完包含关系后，相邻三根K线只有四种组合：', 't')
    kinds = [
        ('上升K线', [(8, 12), (10, 14), (12, 16)], '高低点依次抬高'),
        ('顶分型', [(10, 13), (12, 16), (11, 14)], '中间最高'),
        ('下降K线', [(12, 16), (10, 14), (8, 12)], '高低点依次降低'),
        ('底分型', [(11, 14), (8, 12), (10, 13)], '中间最低'),
    ]
    for k, (name, sp, note) in enumerate(kinds):
        x0 = 10 + k * 187
        p = g.panel(x0, 300, 179, 112, 7, 17, 3, pad_l=8, pad_r=8, pad_t=10, pad_b=18)
        p.bars(sp)
        if name in ('顶分型', '底分型'):
            p.bar(1, sp[1][0], sp[1][1], 'khl')
        g.text(x0 + 89, 296, name, 'tb', 'middle')
        g.text(x0 + 89, 428, note, 'ts', 'middle')
    g.caption('第62课：上升的一笔＝底分型＋上升K线＋顶分型；下降的一笔＝顶分型＋下降K线＋底分型。')
    return g


